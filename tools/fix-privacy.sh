#!/system/bin/sh
#
# fix-privacy.sh — запустил и забыл.
#
# Делает то, что реально мешает следить за телефоном. Само.
# Ничего не ломает, всё обратимо.

set -u

G=''; R=''; Y=''; N=''
if [ -t 1 ]; then G=$(printf '\033[32m'); R=$(printf '\033[31m'); Y=$(printf '\033[33m'); N=$(printf '\033[0m'); fi

echo
echo "================================================"
echo "  Настройка приватности телефона"
echo "================================================"
echo

if [ "$(id -u 2>/dev/null)" != "0" ]; then
    echo "${R}Нужны права root.${N}"
    echo "Запусти так:   su -c 'sh $0'"
    echo
    exit 1
fi

DONE=0
LEFT=0

# ---------------------------------------------------------------- шаг 1 ---

echo "${Y}[1/3]${N} Разрешение экрана"

OV="$(wm size 2>/dev/null | grep -c 'Override')"
OVD="$(wm density 2>/dev/null | grep -c 'Override')"

if [ "$OV" = "0" ] && [ "$OVD" = "0" ]; then
    echo "      ${G}Уже в порядке.${N}"
    DONE=$((DONE + 1))
else
    echo "      Найдена проблема: экран настроен на нестандартный размер."
    echo "      Такого размера нет ни у одного телефона в продаже, поэтому"
    echo "      твой телефон узнаётся по нему как по номеру."
    echo
    echo "      Исправляю..."
    wm size reset 2>/dev/null
    wm density reset 2>/dev/null

    if [ "$(wm size 2>/dev/null | grep -c 'Override')" = "0" ]; then
        echo "      ${G}Готово.${N} Картинка станет чуть мельче — так и должно быть."
        DONE=$((DONE + 1))
    else
        echo "      ${R}Не получилось.${N} Попробуй вручную: wm size reset"
        LEFT=$((LEFT + 1))
    fi
fi
echo

# ---------------------------------------------------------------- шаг 2 ---

echo "${Y}[2/3]${N} Рекламный номер телефона"
echo "      Это самое важное. У телефона есть рекламный номер, по которому"
echo "      его узнают все приложения сразу. Он важнее всего остального"
echo "      вместе взятого. Его надо удалить — вручную, через настройки."
echo

if am start -a com.google.android.gms.settings.ADS_PRIVACY >/dev/null 2>&1 ||
   am start -n com.google.android.gms/.ads.settings.AdsSettingsActivity >/dev/null 2>&1; then
    echo "      ${G}Открыл нужный экран настроек.${N}"
    echo "      Нажми там:  «Удалить рекламный идентификатор»"
else
    echo "      Не смог открыть сам. Зайди руками:"
    echo "      Настройки -> Безопасность и конфиденциальность -> Ещё ->"
    echo "      Реклама -> Удалить рекламный идентификатор"
fi
LEFT=$((LEFT + 1))
echo

# ---------------------------------------------------------------- шаг 3 ---

echo "${Y}[3/3]${N} Проверка"

MODS=0
for m in /data/adb/modules/*/; do
    [ -d "$m" ] && MODS=$((MODS + 1))
done
echo "      Модулей Magisk установлено: $MODS"

DBG="$(getprop 2>/dev/null | grep -cE '^\[(debug|ro\.surface_flinger)\.')"
if [ "$DBG" -gt 0 ]; then
    echo "      ${Y}Модули для разгона игр добавили $DBG необычных настроек.${N}"
    echo "      По ним телефон тоже узнаётся. Если игры не важнее приватности —"
    echo "      отключи GPUTurboBoost и pubgfpsunlocker в приложении Magisk."
else
    echo "      ${G}Лишних настроек нет.${N}"
fi
echo

# ----------------------------------------------------------------- итог ---

echo "================================================"
echo "  Итог"
echo "================================================"
echo
echo "  Сделано автоматически: $DONE"
echo "  Осталось нажать руками: $LEFT"
echo
echo "  Главное: удали рекламный номер в открывшихся настройках."
echo "  Без этого остальное почти не имеет смысла."
echo
echo "  Есть ещё один шаг, но он разлогинит часть приложений."
echo "  Если готов к этому:   sh $0 --sbros-nomerov"
echo

# ------------------------------------------------------- необязательный шаг ---

if [ "${1:-}" = "--sbros-nomerov" ]; then
    echo "================================================"
    echo "  Сброс внутренних номеров приложений"
    echo "================================================"
    echo
    echo "  У каждого приложения есть свой номер твоего телефона."
    echo "  Он не меняется, даже если удалить и поставить приложение заново."
    echo "  Сброс делает так, будто телефон новый."
    echo
    echo "  ${R}ВАЖНО: часть приложений тебя разлогинит.${N}"
    echo "  Банк, госуслуги и игры могут попросить войти заново."
    echo "  Копия сохранится, откатить можно."
    echo
    echo "  Запусти это, если согласен:"
    echo "     sh $(dirname "$0")/privacy-actions.sh ssaid --all --apply"
    echo
fi
